package api

import (
	"errors"
	"net/http"
	"strings"
	"time"

	"github.com/ltpara/ds-chcast/server/internal/account"
	"github.com/ltpara/ds-chcast/server/internal/identity"
	"github.com/ltpara/ds-chcast/server/internal/registry"
)

// hostAuditRequest is one inbound event reported by the host itself. The host
// key that owns the id signs the canonical fields, so the server key alone is
// not enough to fabricate a host-side record.
type hostAuditRequest struct {
	Kind         string `json:"kind"`
	AuditRef     string `json:"audit_ref"`
	StartedAtMS  int64  `json:"started_at_ms"`
	EndedAtMS    int64  `json:"ended_at_ms"`
	Direction    string `json:"direction"`
	Name         string `json:"name"`
	Size         int64  `json:"size"`
	OccurredAtMS int64  `json:"occurred_at_ms"`
	Success      *bool  `json:"success"`
	Detail       string `json:"detail"`
	Timestamp    int64  `json:"timestamp"`
	Signature    string `json:"signature"`
}

// recordHostAudit stores a host-signed inbound session or finished file. The
// audit_ref is generated by the viewer and carried in Hello, so the viewer's
// account report and the host's record merge into one row.
func (s *server) recordHostAudit(w http.ResponseWriter, r *http.Request) {
	if !s.authorized(r) {
		writeError(w, http.StatusUnauthorized, "server key was not accepted")
		return
	}
	if s.cfg.Accounts == nil {
		writeError(w, http.StatusServiceUnavailable, accountUnavailable)
		return
	}
	hostID := strings.TrimSpace(r.PathValue("id"))
	if !registry.ValidID(hostID) {
		writeError(w, http.StatusBadRequest, "host id must be 1..64 characters of [A-Za-z0-9_.-]")
		return
	}
	var req hostAuditRequest
	if err := decodeBody(w, r, &req); err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	record, ok := s.cfg.Registry.Identity(hostID)
	if !ok {
		writeError(w, http.StatusNotFound, "unknown host")
		return
	}
	pub, err := identity.ParsePublicKey(record.PublicKey)
	if err != nil {
		s.cfg.Logger.Error("host audit identity", "id", hostID, "error", err)
		writeError(w, http.StatusInternalServerError, "host identity is unreadable")
		return
	}
	now := time.Now()
	signedAt := time.Unix(req.Timestamp, 0)
	if req.Timestamp == 0 || now.Sub(signedAt) > maxSkew || signedAt.Sub(now) > maxSkew {
		writeError(w, http.StatusUnauthorized, "audit timestamp is outside the allowed window")
		return
	}
	success := true
	if req.Success != nil {
		success = *req.Success
	}
	switch strings.TrimSpace(req.Kind) {
	case "session":
		msg := identity.HostAuditSessionMessage(
			hostID, req.AuditRef, req.StartedAtMS, req.EndedAtMS, success, req.Detail)
		if !identity.Verify(pub, msg, req.Signature) {
			writeError(w, http.StatusUnauthorized, "audit signature was not accepted")
			return
		}
		var startedAt, endedAt time.Time
		if req.StartedAtMS > 0 {
			startedAt = time.UnixMilli(req.StartedAtMS)
		}
		if req.EndedAtMS > 0 {
			endedAt = time.UnixMilli(req.EndedAtMS)
		}
		event, err := s.cfg.Accounts.RecordHostConnection(
			hostID, req.AuditRef, startedAt, endedAt, success, req.Detail)
		if err != nil {
			if errors.Is(err, account.ErrInvalidConnection) {
				writeError(w, http.StatusBadRequest, "session report is invalid")
				return
			}
			s.cfg.Logger.Error("host session audit", "id", hostID, "error", err)
			writeError(w, http.StatusInternalServerError, "could not store the session report")
			return
		}
		writeJSON(w, http.StatusCreated, connectionToView(event))
	case "file":
		msg := identity.HostAuditFileMessage(
			hostID, req.AuditRef, req.Direction, req.Name, req.Size,
			req.OccurredAtMS, success, req.Detail)
		if !identity.Verify(pub, msg, req.Signature) {
			writeError(w, http.StatusUnauthorized, "audit signature was not accepted")
			return
		}
		var occurredAt time.Time
		if req.OccurredAtMS > 0 {
			occurredAt = time.UnixMilli(req.OccurredAtMS)
		}
		event, err := s.cfg.Accounts.RecordHostFileTransfer(
			hostID, req.AuditRef, req.Direction, req.Name, req.Size,
			occurredAt, success, req.Detail)
		if err != nil {
			if errors.Is(err, account.ErrInvalidTransfer) {
				writeError(w, http.StatusBadRequest, "file report is invalid")
				return
			}
			s.cfg.Logger.Error("host file audit", "id", hostID, "error", err)
			writeError(w, http.StatusInternalServerError, "could not store the file report")
			return
		}
		writeJSON(w, http.StatusCreated, fileTransferToView(event))
	default:
		writeError(w, http.StatusBadRequest, "kind must be session or file")
	}
}
