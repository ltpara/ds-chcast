// FFmpeg's bitstream readers may look past the last byte of an input buffer,
// so libavcodec requires AV_INPUT_BUFFER_PADDING_SIZE readable zero bytes
// after every access unit. The decoder hands it a packet whose data points
// straight at the caller's buffer (no padding); avcodec_send_packet copies
// such non-refcounted packets into its own padded storage.
//
// This test pins that contract with a real access unit truncated mid-slice and
// placed flush against a PROTECT_NONE page. A decoder that ever reads the
// caller's memory past `size` faults here instead of silently corrupting a
// heap block; any decode outcome is acceptable, a crash of the test is not.
