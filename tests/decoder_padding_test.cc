int main() {
    SYSTEM_INFO info{};
    GetSystemInfo(&info);
    const SIZE_T page = info.dwPageSize;
    auto* region = static_cast<unsigned char*>(
        VirtualAlloc(nullptr, page * 2, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE));
    if (!region) {
        std::printf("FAIL VirtualAlloc\n");
        return 1;
    }
    DWORD previous = 0;
    if (!VirtualProtect(region + page, page, PAGE_NOACCESS, &previous)) {
        std::printf("FAIL VirtualProtect\n");
        VirtualFree(region, 0, MEM_RELEASE);
        return 1;
    }
    const size_t size = sizeof(kAccessUnit);
    unsigned char* data = region + page - size;
    std::memcpy(data, kAccessUnit, size);

    chast::DecoderConfig config;
    config.codec = chast::VideoCodec::H264;
    std::string error;
    std::unique_ptr<chast::IVideoDecoder> decoder = chast::create_decoder(config, &error);
    if (!decoder) {
        std::printf("FAIL create_decoder: %s\n", error.c_str());
        VirtualFree(region, 0, MEM_RELEASE);
        return 1;
    }
    std::vector<chast::DecodedFrame> frames;
    const chast::Error decoded = decoder->decode(data, size, 0, true, frames);
    // The access unit is short, so its content decides whether a picture
    // completes. Reaching this line is the check: the guard page was never
    // touched.
    std::printf("ok   an unpadded access unit against a guard page is not overread\n");
    std::printf("     decoder answered: %s\n", decoded.to_string().c_str());
    VirtualFree(region, 0, MEM_RELEASE);
    return 0;
}
