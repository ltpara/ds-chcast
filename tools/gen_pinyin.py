#!/usr/bin/env python3
"""Generate the pinyin-initial table from the GB2312 level-1 ordering.

Level-1 hanzi (3,755 common characters) are laid out by pinyin in GB2312, so
each initial owns one contiguous code range. The generated Dart file groups
the characters by initial; nothing else is copied from any pinyin library.
"""
import io

RANGES = [
    ('a', 0xB0A1, 0xB0C4), ('b', 0xB0C5, 0xB2C0), ('c', 0xB2C1, 0xB4ED),
    ('d', 0xB4EE, 0xB6E9), ('e', 0xB6EA, 0xB7A1), ('f', 0xB7A2, 0xB8C0),
    ('g', 0xB8C1, 0xB9FD), ('h', 0xB9FE, 0xBBF6), ('j', 0xBBF7, 0xBFA5),
    ('k', 0xBFA6, 0xC0AB), ('l', 0xC0AC, 0xC2E7), ('m', 0xC2E8, 0xC4C2),
    ('n', 0xC4C3, 0xC5B5), ('o', 0xC5B6, 0xC5BD), ('p', 0xC5BE, 0xC6D9),
    ('q', 0xC6DA, 0xC8BA), ('r', 0xC8BB, 0xC8F5), ('s', 0xC8F6, 0xCBF9),
    ('t', 0xCBFA, 0xCDD9), ('w', 0xCDDA, 0xCEF3), ('x', 0xCEF4, 0xD188),
    ('y', 0xD189, 0xD4D0), ('z', 0xD4D1, 0xD7F9),
]

lines = []
total = 0
for initial, lo, hi in RANGES:
    chars = []
    for code in range(lo, hi + 1):
        try:
            chars.append(bytes([code >> 8, code & 0xFF]).decode('gb2312'))
        except UnicodeDecodeError:
            continue
    total += len(chars)
    lines.append("  '%s': '%s'," % (initial, ''.join(chars)))

assert total == 3755, total
output = (
    "// Generated by tools/gen_pinyin.py from the GB2312 level-1 hanzi order\n"
    "// (3,755 common characters). Do not edit by hand.\n"
    "const Map<String, String> pinyinInitialGroups = <String, String>{\n"
    + '\n'.join(lines) + '\n};\n'
)
with io.open('app/lib/pinyin_initials.dart', 'w', encoding='utf-8', newline='\n') as handle:
    handle.write(output)
print('wrote app/lib/pinyin_initials.dart with', total, 'characters')
