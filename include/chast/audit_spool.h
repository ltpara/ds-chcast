#pragma once

// Host-side inbound audit spool.
//
// The host appends one JSON object per completed session or received file to
// a JSONL file. chast-tunnel host tails the file, signs each record with the
// device key and forwards it to the rendezvous service, so an audit record
// exists even when the viewer's own report never made it. The host does not
// put its device id or key in the file: the agent supplies both, which keeps a
// copied spool from being replayed against the original id.

#include <cstdint>
#include <string>

namespace chast {

struct AuditSessionRecord {
    // Lowercase hex from the viewer's Hello, or a host-generated id when the
    // viewer sent none; the host always records the session.
    std::string audit_ref;
    // True when audit_ref was generated by the host, so this record has no
    // viewer half to merge with. The service's stored row shows that through
    // source=host and an empty username.
    bool viewer_ref_absent = false;
    int64_t started_at_ms = 0;
    int64_t ended_at_ms = 0;
    bool success = true;
    std::string detail;
};

struct AuditFileRecord {
    std::string audit_ref;
    bool viewer_ref_absent = false;
    // "upload" for a viewer -> host file.
    std::string direction;
    std::string name;
    uint64_t size = 0;
    int64_t occurred_at_ms = 0;
    bool success = true;
    std::string detail;
};

// A Hello the host refused. No session exists and the viewer may not have
// sent an audit reference, so the record is identified by the source address
// and the refusal instead.
struct AuditDenialRecord {
    // The transport's "ip:port", or empty when it reported none.
    std::string address;
    // The AccessDenial value, kept numeric so the service need not mirror the
    // enum. The agent signs it with the other fields.
    int code = 0;
    int64_t occurred_at_ms = 0;
    std::string detail;
};

// Appends one line. Opens and closes the file per record so the agent can
// delete it between writes; missing directories are the caller's problem (the
// default spool sits next to host.ini, which already exists). The spool
// rotates to "<path>.1" past 5 MiB so a host without an agent cannot grow it
// without bound; only one backup is kept.
bool append_audit_session(const std::string& spool_path, const AuditSessionRecord& record,
                          std::string* error = nullptr);
bool append_audit_file(const std::string& spool_path, const AuditFileRecord& record,
                       std::string* error = nullptr);
bool append_audit_denial(const std::string& spool_path, const AuditDenialRecord& record,
                         std::string* error = nullptr);

}  // namespace chast
